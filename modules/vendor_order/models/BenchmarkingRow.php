    public function multipleUpdate(string $data)
    {
        try {
            $result = ['processed' => 0];

            $data = json_decode($data, true);
            if (empty($data)) {
                return ['success' => false, 'error' => 'Пустые данные'];
            }

            $data = static::collectFromArray($data);

            foreach ($data as $row) {
                $model = BenchmarkingRowTable::findOne($row->id ?? 0);

                if ($model) {
                    // Обновляем основные поля
                    $model->status = $row->status ?? $model->status;
                    $model->request = $row->request ?? $model->request;
                    $model->save();

                    // Обновляем product_row
                    if ($model->productRow) {
                        $model->productRow->brand = $row->brand ?? $model->productRow->brand;
                        $model->productRow->type_machine = $row->typeMachine ?? $model->productRow->type_machine;
                        $model->productRow->save();
                    }

                    // Сохраняем вариации
                    if (!empty($row->variations) && is_array($row->variations)) {
                        foreach ($row->variations as $variation) {
                            if ($variation instanceof \app\modules\vendor_order\models\benchmarking\SupplierRow) {
                                $variation->save();
                            }
                        }
                    }

                    $result['processed']++;
                }
            }

            $result['success'] = true;
            return $result;

        } catch (\Exception $e) {
            return [
                'success' => false,
                'error' => $e->getMessage(),
                'trace' => $e->getTraceAsString()
            ];
        }
    }
